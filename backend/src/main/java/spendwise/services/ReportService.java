package spendwise.services;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.nio.charset.StandardCharsets;
import java.time.LocalDate;
import java.time.YearMonth;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import spendwise.util.Util;

/**
 * Builds the monthly PDF report. A tiny PDF writer is included (one A4/Letter page, built-in fonts),
 * so no PDF library is needed. Built-in PDF fonts cannot print the rupee sign, so "Rs." is used.
 */
public final class ReportService {
    private ReportService() { }

    /** 1234567.5 -> "Rs. 12,34,567.50" (Indian digit grouping). */
    static String rs(double n) {
        String[] parts = BigDecimal.valueOf(Math.abs(n)).setScale(2, RoundingMode.HALF_UP).toPlainString().split("\\.");
        String ip = parts[0], grouped = ip;
        if (ip.length() > 3) {
            String last3 = ip.substring(ip.length() - 3), rest = ip.substring(0, ip.length() - 3);
            StringBuilder sb = new StringBuilder();
            while (rest.length() > 2) { sb.insert(0, "," + rest.substring(rest.length() - 2)); rest = rest.substring(0, rest.length() - 2); }
            grouped = sb.insert(0, rest).append(",").append(last3).toString();
        }
        return "Rs. " + (n < 0 ? "-" : "") + grouped + "." + parts[1];
    }

    @SuppressWarnings("unchecked")
    public static byte[] buildPdf(String month, Map<String, Object> d) {
        double income = Util.num(d.get("income")), expenses = Util.num(d.get("expenses")), goalSavings = Util.num(d.get("goalSavings"));
        List<Map<String, Object>> categories = (List<Map<String, Object>>) d.get("categories");
        Object budget = d.get("budget");

        Pdf pdf = new Pdf();
        String label = YearMonth.parse(month).format(DateTimeFormatter.ofPattern("MMMM yyyy", Locale.ENGLISH));
        double y = 50;
        pdf.text(50, y, 22, true, 0.31, 0.27, 0.90, "SpendWise Monthly Report");
        y += 32;
        pdf.text(50, y, 12, false, 0.33, 0.33, 0.33, label);
        y += 36;
        pdf.text(50, y, 14, false, 0, 0, 0, "Summary");
        y += 24;
        List<String> lines = new ArrayList<>();
        lines.add("Total income: " + rs(income));
        lines.add("Total expenses: " + rs(expenses));
        lines.add("Net savings: " + rs(income - expenses));
        lines.add("Added to savings goals: " + rs(goalSavings));
        lines.add("Monthly budget: " + (budget == null ? "Not set"
            : rs(Util.num(budget)) + " (" + String.format(Locale.ROOT, "%.0f", expenses / Util.num(budget) * 100) + "% used)"));
        for (String l : lines) { pdf.text(50, y, 11, false, 0, 0, 0, l); y += 16; }

        y += 20;
        pdf.text(50, y, 14, false, 0, 0, 0, "Expenses by category");
        y += 24;
        if (categories.isEmpty()) pdf.text(50, y, 11, false, 0, 0, 0, "No expenses recorded this month.");
        for (Map<String, Object> c : categories) {
            double total = Util.num(c.get("total"));
            pdf.text(50, y, 11, false, 0, 0, 0, String.valueOf(c.get("category")));
            pdf.text(200, y, 11, false, 0, 0, 0, Util.jsNum(Util.num(c.get("entries"))) + " entries");
            pdf.text(300, y, 11, false, 0, 0, 0, rs(total));
            pdf.text(450, y, 11, false, 0, 0, 0, expenses != 0 ? String.format(Locale.ROOT, "%.1f", total / expenses * 100) + "%" : "");
            y += 16;
        }
        y += 40;
        pdf.text(50, y, 9, false, 0.53, 0.53, 0.53, "Generated by SpendWise on " + LocalDate.now().format(DateTimeFormatter.ofPattern("dd/MM/yyyy")));
        return pdf.build();
    }

    /** Minimal single-page PDF writer: text only, Helvetica and Helvetica-Bold. */
    private static final class Pdf {
        private final StringBuilder content = new StringBuilder();

        /** (x, top) are measured in points from the top-left corner of a 612 x 792 page. */
        void text(double x, double top, double size, boolean bold, double r, double g, double b, String s) {
            double y = 792 - top - size;
            content.append(String.format(Locale.ROOT, "%.2f %.2f %.2f rg BT /%s %.1f Tf %.1f %.1f Td (%s) Tj ET\n", r, g, b, bold ? "F2" : "F1", size, x, y, escape(s)));
        }

        private static String escape(String s) {
            StringBuilder sb = new StringBuilder();
            for (char c : s.toCharArray()) {
                if (c == '\\' || c == '(' || c == ')') sb.append('\\').append(c);
                else if (c < 32 || c > 126) sb.append('?');
                else sb.append(c);
            }
            return sb.toString();
        }

        byte[] build() {
            byte[] stream = content.toString().getBytes(StandardCharsets.ISO_8859_1);
            List<String> objs = new ArrayList<>();
            objs.add("<< /Type /Catalog /Pages 2 0 R >>");
            objs.add("<< /Type /Pages /Kids [3 0 R] /Count 1 >>");
            objs.add("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>");
            objs.add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");
            objs.add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>");
            objs.add("<< /Length " + stream.length + " >>\nstream\n" + new String(stream, StandardCharsets.ISO_8859_1) + "endstream");

            StringBuilder out = new StringBuilder("%PDF-1.4\n");
            List<Integer> offsets = new ArrayList<>();
            for (int i = 0; i < objs.size(); i++) {
                offsets.add(out.length());
                out.append(i + 1).append(" 0 obj\n").append(objs.get(i)).append("\nendobj\n");
            }
            int xref = out.length();
            out.append("xref\n0 ").append(objs.size() + 1).append("\n0000000000 65535 f \n");
            for (int off : offsets) out.append(String.format("%010d 00000 n \n", off));
            out.append("trailer\n<< /Size ").append(objs.size() + 1).append(" /Root 1 0 R >>\nstartxref\n").append(xref).append("\n%%EOF\n");
            return out.toString().getBytes(StandardCharsets.ISO_8859_1);
        }
    }
}
